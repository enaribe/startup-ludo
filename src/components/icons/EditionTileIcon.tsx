export const EditionTileIcon = memo(function EditionTileIcon({
  editionId,
  editionName,
  size = 34,
  color,
}: EditionTileIconProps) {
  const variant = useMemo(
    () => resolveEditionTileIconVariant(editionId, editionName),
    [editionId, editionName]
  );

  switch (variant) {
    case 'classic':
      return <EditionClassicIcon color={color} size={size} />;
    case 'agriculture':
      return <SectorActivityIcon size={size} color={color} />;
    case 'culture':
      return <EditionCultureIcon color={color} size={size} />;
    case 'education':
      return <EditionEducationIcon color={color} size={size} />;
    case 'fintech':
      return <EditionFintechIcon color={color} size={size} />;
    case 'health':
      return <EditionHealthIcon color={color} size={size} />;
    case 'sport':
      return <EditionSportIcon color={color} size={size} />;
    default:
      return <EditionClassicIcon color={color} size={size} />;
  }
});
