export type EditionTileIconVariant =
  | 'classic'
  | 'agriculture'
  | 'culture'
  | 'education'
  | 'fintech'
  | 'health'
  | 'sport'
  | 'default';

function stripDiacritics(s: string): string {
  return s.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
}

/** Associe une édition (id / nom) à l’icône SVG du carreau de choix */
export function resolveEditionTileIconVariant(editionId: string, editionName: string): EditionTileIconVariant {
  const id = stripDiacritics(editionId.toLowerCase());
  const name = stripDiacritics(editionName.toLowerCase());

  if (id === 'classic' || name.includes('classique')) return 'classic';
  if (
    id.includes('agriculture') ||
    id.includes('agri') ||
    name.includes('agriculture') ||
    name.includes('agritech')
  ) {
    return 'agriculture';
  }
  if (id.includes('culture') || name.includes('culture')) return 'culture';
  if (id.includes('education') || name.includes('education')) return 'education';
  if (id.includes('fintech') || name.includes('fintech')) return 'fintech';
  if (
    id.includes('sante') ||
    name.includes('sante') ||
    name.includes('bien-etre') ||
    name.includes('bien etre')
  ) {
    return 'health';
  }
  if (id.includes('sport') || id.includes('fitness') || name.includes('sport') || name.includes('fitness')) {
    return 'sport';
  }
  return 'default';
}

