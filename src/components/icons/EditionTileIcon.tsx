function SvgScale({
  vbW,
  vbH,
  size,
  children,
}: {
  vbW: number;
  vbH: number;
  size: number;
  children: ReactNode;
}) {
  const h = size;
  const w = (vbW / vbH) * size;
  return (
    <Svg width={w} height={h} viewBox={`0 0 ${vbW} ${vbH}`} fill="none">
      {children}
    </Svg>
  );
}

